"""Checks the generator's automatic graph layout, sections, notes and function docs (plan Task 1a).

    python -I tools/bpgen/test_layout.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bpgen import BOOL, FLOAT, INT, STRING, Blueprint, Graph, Pin  # noqa: E402

MATH, SYS = "KismetMathLibrary", "KismetSystemLibrary"


def rect(n):
    return n.x, n.y, n.x + n.width, n.y + n.height


def contains(outer, inner):
    return outer[0] <= inner[0] and outer[1] <= inner[1] and outer[2] >= inner[2] and outer[3] >= inner[3]


def test_event_graph_layout():
    g = Graph("BP_T", "EventGraph")
    g.section("Tick")
    ev = g.tick()
    b = g.branch()
    g.exec(ev, b)
    yes = g.call_static(SYS, "PrintString", inputs=[Pin("InString", STRING, default="yes")])
    no = g.call_static(SYS, "PrintString", inputs=[Pin("InString", STRING, default="no")])
    g.link(b, "then", yes, "execute")
    g.link(b, "else", no, "execute")
    gt = g.call_static(MATH, "Greater_FloatFloat", inputs=[Pin("A", FLOAT), Pin("B", FLOAT, default="1")],
                       outputs=[Pin("ReturnValue", BOOL, "out")], pure=True)
    g.link(gt, "ReturnValue", b, "Condition")
    health = g.var_get("Health", FLOAT)
    g.link(health, "Health", gt, "A")
    g.note(b, "hurt?")
    text = g.text()

    assert b.x > ev.x, "exec flow runs left to right"
    assert yes.x > b.x and no.x > b.x
    assert no.y > yes.y, "the else branch starts a new row below the then branch"
    assert gt.x < b.x, "a pure input sits left of its consumer"
    assert health.x < gt.x, "a deeper pure input sits further left"
    assert g.overlaps() == [], g.overlaps()
    comments = [n for n in g.nodes if n.cls.endswith("EdGraphNode_Comment")]
    assert len(comments) == 1, comments
    assert 'NodeComment="Tick"' in comments[0].text()
    box = rect(comments[0])
    for n in g.nodes:
        if n is not comments[0]:
            assert contains(box, rect(n)), (n.name, box, rect(n))
    assert 'NodeComment="hurt?"' in b.text() and "bCommentBubbleVisible=True" in b.text()
    assert "Generated by" not in text


def test_function_graph_layout():
    bp = Blueprint("/Game/T/BP_T", "/Script/Engine.Actor", description="A test actor.")
    f = bp.function("Add", inputs=["A:int"], outputs=["R:int"], doc="Adds one to A.")
    n = f.call_static(MATH, "Add_IntInt", inputs=[Pin("A", INT), Pin("B", INT, default="1")],
                      outputs=[Pin("ReturnValue", INT, "out")], pure=True)
    f.link_entry("A", n, "A")
    f.link_result(n, "ReturnValue", "R")
    f.link_entry("then", "result", "execute")
    f.text()
    assert f.layout_info["entry"] == [0, 0]
    assert f.layout_info["result"][0] > max(node.x + node.width for node in f.nodes if not node.cls.endswith("EdGraphNode_Comment"))
    comments = [c for c in f.nodes if c.cls.endswith("EdGraphNode_Comment")]
    assert len(comments) == 1 and 'NodeComment="Adds one to A."' in comments[0].text()
    assert contains(rect(comments[0]), (0, 0, 1, 1)), "the function box includes the entry node"
    assert f.overlaps() == []
    m = bp.manifest()
    assert m["description"] == "A test actor."
    assert m["functions"][0]["doc"] == "Adds one to A."
    assert m["graphs"][0]["layout"]["entry"] == [0, 0] and m["graphs"][0]["layout"]["result"] is not None


def test_function_without_outputs_has_no_result():
    bp = Blueprint("/Game/T/BP_T", "/Script/Engine.Actor")
    f = bp.function("Ping")
    p = f.call_static(SYS, "PrintString", inputs=[Pin("InString", STRING, default="ping")])
    f.link_entry("then", p, "execute")
    f.text()
    assert f.layout_info["result"] is None
    assert p.x > 0, "nodes start right of the entry node"


