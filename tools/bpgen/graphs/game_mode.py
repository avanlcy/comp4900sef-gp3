    idx2 = g.var_get_on(CPC, "CheckpointIndex", INT)
    g.link_entry("Checkpoint", idx2, "self")
    is0 = compare(g, "EqualEqual_IntInt", INT, b="0")
    g.link(idx2, "CheckpointIndex", is0, "A")
