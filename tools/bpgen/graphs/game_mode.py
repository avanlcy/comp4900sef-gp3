    g.link(b_, "Item", ahead, "A")
    g.link(a_, "Item", ahead, "B")
    bs = branch_on(g, (ahead, "ReturnValue"), (inner, "LoopBody"))
    sw = g.call_array(ARR, "Array_Swap", racer_elem(), inputs=[Pin("FirstIndex", INT), Pin("SecondIndex", INT)], pure=False)
    g.link(ranked(), "Ranked", sw, "TargetArray")
    g.link(inner, "Index", sw, "FirstIndex")
    g.link(j1, "ReturnValue", sw, "SecondIndex")
