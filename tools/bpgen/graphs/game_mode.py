# ---------- small helpers ----------
def name_of_entry(g, pin):
    n = g.call_static("KismetSystemLibrary", "GetDisplayName", inputs=[obj_pin("Object", "/Script/CoreUObject.Object")],
                      outputs=[Pin("ReturnValue", STRING, "out")], pure=True)
    g.link_entry(pin, n, "Object")
    return (n, "ReturnValue")


def link(g: Graph, src, dst: Node, pin: str):
    g.link(src[0], src[1], dst, pin)


def get_on(g, cls, var, cat, obj, sub=None, container=None):
    n = g.var_get_on(cls, var, cat, sub, container=container)
    link(g, obj, n, "self")
    return n


def set_on(g, cls, var, cat, obj, value=None, default=None, sub=None):
    n = g.var_set_on(cls, var, cat, default=default, sub_object=sub)
    link(g, obj, n, "self")
    if value:
        link(g, value, n, var)
    return n


def add_int_on(g, cls, var, obj, delta=None, delta_src=None):
    cur = get_on(g, cls, var, INT, obj)
    add = math2(g, "Add_IntInt", INT, b=delta)
    g.link(cur, var, add, "A")
    if delta_src:
        link(g, delta_src, add, "B")
    return set_on(g, cls, var, INT, obj, value=(add, "ReturnValue"))


def call(g, cls, fn, obj, inputs=None, outputs=None, pure=False, **defaults):
    n = g.call_on(cls, fn, inputs=inputs, outputs=outputs, pure=pure, **defaults)
    link(g, obj, n, "self")
    return n


def valid(g, src) -> Node:
    v = is_valid(g)
    link(g, src, v, "Object")
    return v


def branch_on(g, cond_src, prev=None) -> Node:
    b = g.branch()
    link(g, cond_src, b, "Condition")
    if prev:
        g.link(prev[0], prev[1], b, "execute")
    return b


def find_racer(g, c_src) -> Node:
    n = g.call_self("FindRacer", inputs=[obj_pin("C", CONTROLLER)], outputs=[obj_pin("Racer", RC, "out")], pure=True)
    link(g, c_src, n, "C")
    return n


def actor_loc(g, obj) -> Node:
    return call(g, ACTOR, "K2_GetActorLocation", obj, outputs=[struct_pin("ReturnValue", VECTOR, "out")], pure=True)


def racer_elem():
    return Pin("e", OBJECT, sub_object=cls_ref(RC))


def ret(g, **values):
    """Function result with literal defaults, e.g. ret(g, ReturnValue='false')."""
    return g.function_result([Pin(k, "bool" if v in ("true", "false") else STRING, default=v) for k, v in values.items()])


# ---------- game state ----------
def build_state() -> Blueprint:
    bp = Blueprint(BP_GS, parent=GAME_STATE_BASE)
    R = "Dead Fire|Race"
    bp.variable("RemainingTime", "float", "120", R)
    bp.variable("bRaceActive", "bool", "true", R)
    bp.variable("Result", struct_spec(S_RESULT), "", R)

    # GetRemainingTimeString -> "m:ss"
    g = bp.function("GetRemainingTimeString", outputs=["Text:string"], pure=True)
    t = g.var_get("RemainingTime", FLOAT)
    ceil = g.call_static(MATH, "FCeil", inputs=[Pin("A", FLOAT)], outputs=[Pin("ReturnValue", INT, "out")], pure=True)
    g.link(t, "RemainingTime", ceil, "A")
    total = g.call_static(MATH, "Max", inputs=[Pin("A", INT), Pin("B", INT, default="0")], outputs=[Pin("ReturnValue", INT, "out")], pure=True)
    g.link(ceil, "ReturnValue", total, "A")
    mins = math2(g, "Divide_IntInt", INT, b="60")
    g.link(total, "ReturnValue", mins, "A")
    secs = math2(g, "Percent_IntInt", INT, b="60")
    g.link(total, "ReturnValue", secs, "A")

    def to_str(src):
        n = g.call_static("KismetStringLibrary", "Conv_IntToString", inputs=[Pin("InInt", INT)], outputs=[Pin("ReturnValue", STRING, "out")], pure=True)
        link(g, src, n, "InInt")
        return n

    lt10 = compare(g, "Less_IntInt", INT, b="10")
    g.link(secs, "ReturnValue", lt10, "A")
    pad = g.call_static(MATH, "SelectString", inputs=[Pin("A", STRING, default="0"), Pin("B", STRING, default=""), Pin("bPickA", BOOL)],
                        outputs=[Pin("ReturnValue", STRING, "out")], pure=True)
    g.link(lt10, "ReturnValue", pad, "bPickA")

    def concat(a, b_src=None, b=None):
        n = g.call_static("KismetStringLibrary", "Concat_StrStr", inputs=[Pin("A", STRING), Pin("B", STRING, default=b)],
                          outputs=[Pin("ReturnValue", STRING, "out")], pure=True)
        link(g, a, n, "A")
        if b_src:
            link(g, b_src, n, "B")
        return n

    s1 = concat((to_str((mins, "ReturnValue")), "ReturnValue"), b=":")
    s2 = concat((s1, "ReturnValue"), b_src=(pad, "ReturnValue"))
    s3 = concat((s2, "ReturnValue"), b_src=(to_str((secs, "ReturnValue")), "ReturnValue"))
    g.link_result(s3, "ReturnValue", "Text")
    g.link_entry("then", "result", "execute")
    return bp


# ---------- game mode ----------
def build_mode() -> Blueprint:
    bp = Blueprint(BP_GM, parent=GAME_MODE_BASE)
    R = "Dead Fire|Race"
    bp.variable("OnFootCharacterClass", "class:" + CC, "", R, editable=True)
    bp.variable("RaceTimeLimit", "float", "120", R, editable=True)
    bp.variable("CheckpointTimeBonus", "float", "8", R, editable=True)
    bp.variable("PointsPerLap", "int", "100", R, editable=True)
    bp.variable("PointsPerKill", "int", "50", R, editable=True)
    bp.variable("MaxDeaths", "int", "3", R, editable=True)
    bp.variable("ScoreRequirement", "int", "300", R, editable=True)
    bp.variable("RespawnDelay", "float", "2", R, editable=True)
    bp.variable("OffTrackMargin", "float", "500", R, editable=True)
    bp.variable("OffTrackGraceSeconds", "float", "5", R, editable=True)
    S = "Dead Fire|Race|State"
    bp.variable("RaceState", obj_spec(BP_GS), "", S)
    bp.variable("Checkpoints", "array<%s>" % obj_spec(BP_CHECKPOINT), "", S)
    bp.variable("Tracks", "array<%s>" % obj_spec(BP_TRACK), "", S)
    bp.variable("MainTrack", obj_spec(BP_TRACK), "", S)
    bp.variable("PendingRespawnRacer", "object:" + CONTROLLER, "", S)
    bp.variable("RespawnDueTime", "float", "-1", S)
    bp.dispatcher("OnRaceEnded", ["Reason:" + enum_spec(E_END_REASON), "bPassed:bool"])
    bp.dispatcher("OnRacerRespawned", ["Racer:object:" + CONTROLLER])
    bp.default("OnFootCharacterClass", "class:" + BP_CHARACTER)
    bp.default("DefaultPawnClass", "class:" + BP_VEHICLE)
    bp.default("PlayerControllerClass", "class:" + BP_PC)
    bp.default("GameStateClass", "class:" + BP_GS)
    bp.default("HUDClass", "class:" + BP_HUD)

    race_state = lambda g: (g.var_get("RaceState", OBJECT, cls_ref(GSC)), "RaceState")
    racer_out = "Racer:object:" + RC

    # FindRacer(C) -> Racer (pure; None when C has no BPC_DFRacer)
    g = bp.function("FindRacer", inputs=["C:object:" + CONTROLLER], outputs=[racer_out], pure=True)
    v = g.call_static("KismetSystemLibrary", "IsValid", inputs=[obj_pin("Object", "/Script/CoreUObject.Object")],
                      outputs=[Pin("ReturnValue", BOOL, "out")], pure=True)
    g.link_entry("C", v, "Object")
    b = g.branch()
    g.link(v, "ReturnValue", b, "Condition")
    g.link_entry("then", b, "execute")
    none = g.function_result([obj_pin("Racer", RC)])
    g.link(b, "else", none, "execute")
    comp = g.call_on(ACTOR, "GetComponentByClass",
                     inputs=[Pin("ComponentClass", "class", sub_object=cls_ref("/Script/Engine.ActorComponent"), default_object=RC)],
                     outputs=[obj_pin("ReturnValue", RC, "out")], pure=True)
    g.link_entry("C", comp, "self")
    cast = g.cast(RC)
    g.link(comp, "ReturnValue", cast, "Object")
    g.link(b, "then", cast, "execute")
    found = g.function_result([obj_pin("Racer", RC)])
    g.link(cast, as_pin(BPC_RACER), found, "Racer")
    g.link(cast, "then", found, "execute")
    g.link(cast, "CastFailed", none, "execute")

    # RegisterCheckpoint(Checkpoint): add once, keep sorted by CheckpointIndex (bubble pass; n is small)
    g = bp.function("RegisterCheckpoint", inputs=["Checkpoint:" + obj_spec(BP_CHECKPOINT)])
    arr = g.var_get("Checkpoints", OBJECT, cls_ref(CPC), container="Array")
    has = g.call_array(ARR, "Array_Contains", Pin("e", OBJECT, sub_object=cls_ref(CPC)),
                       inputs=[Pin("ItemToFind", OBJECT, sub_object=cls_ref(CPC))], outputs=[Pin("ReturnValue", BOOL, "out")])
    g.link(arr, "Checkpoints", has, "TargetArray")
    g.link_entry("Checkpoint", has, "ItemToFind")
    b = g.branch()
    g.link(has, "ReturnValue", b, "Condition")
    g.link_entry("then", b, "execute")
    add = g.call_array(ARR, "Array_Add", Pin("e", OBJECT, sub_object=cls_ref(CPC)),
                       inputs=[Pin("NewItem", OBJECT, sub_object=cls_ref(CPC))], outputs=[Pin("ReturnValue", INT, "out")], pure=False)
    arr2 = g.var_get("Checkpoints", OBJECT, cls_ref(CPC), container="Array")
    g.link(arr2, "Checkpoints", add, "TargetArray")
    g.link_entry("Checkpoint", add, "NewItem")
    g.link(b, "else", add, "execute")
    outer = g.for_loop()
    arr3 = g.var_get("Checkpoints", OBJECT, cls_ref(CPC), container="Array")
    last = g.call_array(ARR, "Array_LastIndex", Pin("e", OBJECT, sub_object=cls_ref(CPC)), outputs=[Pin("ReturnValue", INT, "out")])
    g.link(arr3, "Checkpoints", last, "TargetArray")
    g.link(last, "ReturnValue", outer, "LastIndex")
    g.link(add, "then", outer, "execute")
    inner = g.for_loop()
    lm1 = math2(g, "Subtract_IntInt", INT, b="1")
    g.link(last, "ReturnValue", lm1, "A")
    g.link(lm1, "ReturnValue", inner, "LastIndex")
    g.link(outer, "LoopBody", inner, "execute")

    def cp_index(idx_src):
        a = g.var_get("Checkpoints", OBJECT, cls_ref(CPC), container="Array")
        get = g.call_array(ARR, "Array_Get", Pin("e", OBJECT, sub_object=cls_ref(CPC)), inputs=[Pin("Index", INT)],
                           outputs=[Pin("Item", OBJECT, "out", cls_ref(CPC))])
        g.link(a, "Checkpoints", get, "TargetArray")
        link(g, idx_src, get, "Index")
        return get_on(g, CPC, "CheckpointIndex", INT, (get, "Item"))

    j1 = math2(g, "Add_IntInt", INT, b="1")
    g.link(inner, "Index", j1, "A")
    ia, ib = cp_index((inner, "Index")), cp_index((j1, "ReturnValue"))
    gt = compare(g, "Greater_IntInt", INT)
    g.link(ia, "CheckpointIndex", gt, "A")
    g.link(ib, "CheckpointIndex", gt, "B")
    bs = branch_on(g, (gt, "ReturnValue"), (inner, "LoopBody"))
    sw = g.call_array(ARR, "Array_Swap", Pin("e", OBJECT, sub_object=cls_ref(CPC)),
                      inputs=[Pin("FirstIndex", INT), Pin("SecondIndex", INT)], pure=False)
    a4 = g.var_get("Checkpoints", OBJECT, cls_ref(CPC), container="Array")
    g.link(a4, "Checkpoints", sw, "TargetArray")
    g.link(inner, "Index", sw, "FirstIndex")
    g.link(j1, "ReturnValue", sw, "SecondIndex")
    g.link(bs, "then", sw, "execute")

    # CollectLevelActors: every checkpoint and track in the level; MainTrack = first with bIsMainTrack
    g = bp.function("CollectLevelActors")
    allcp = g.call_static(GAMEPLAY, "GetAllActorsOfClass",
                          inputs=[Pin("WorldContextObject", OBJECT, hidden=True),
                                  Pin("ActorClass", "class", sub_object=cls_ref(ACTOR), default_object=CPC)],
                          outputs=[Pin("OutActors", OBJECT, "out", cls_ref(CPC), container="Array")])
    g.link_entry("then", allcp, "execute")
    loop = g.for_each(Pin("e", OBJECT, sub_object=cls_ref(CPC)))
    g.link(allcp, "OutActors", loop, "Array")
    g.link(allcp, "then", loop, "Exec")
    reg = g.call_self("RegisterCheckpoint", inputs=[obj_pin("Checkpoint", CPC)])
    g.link(loop, "Array Element", reg, "Checkpoint")
    g.link(loop, "LoopBody", reg, "execute")
    alltr = g.call_static(GAMEPLAY, "GetAllActorsOfClass",
                          inputs=[Pin("WorldContextObject", OBJECT, hidden=True),
                                  Pin("ActorClass", "class", sub_object=cls_ref(ACTOR), default_object=TC)],
                          outputs=[Pin("OutActors", OBJECT, "out", cls_ref(TC), container="Array")])
    g.link(loop, "Completed", alltr, "execute")
    st = g.var_set("Tracks", OBJECT, sub_object=cls_ref(TC), container="Array")
    g.link(alltr, "OutActors", st, "Tracks")
    g.exec(alltr, st)
    loop2 = g.for_each(Pin("e", OBJECT, sub_object=cls_ref(TC)))
    tr = g.var_get("Tracks", OBJECT, cls_ref(TC), container="Array")
    g.link(tr, "Tracks", loop2, "Array")
    g.link(st, "then", loop2, "Exec")
    is_main = get_on(g, TC, "bIsMainTrack", BOOL, (loop2, "Array Element"))
    mt = g.var_get("MainTrack", OBJECT, cls_ref(TC))
    no_main = not_bool(g)
    g.link(valid(g, (mt, "MainTrack")), "ReturnValue", no_main, "A")
    both = and_bool(g)
    g.link(is_main, "bIsMainTrack", both, "A")
    g.link(no_main, "ReturnValue", both, "B")
    bm = branch_on(g, (both, "ReturnValue"), (loop2, "LoopBody"))
    smt = g.var_set("MainTrack", OBJECT, sub_object=cls_ref(TC))
    g.link(loop2, "Array Element", smt, "MainTrack")
    g.link(bm, "then", smt, "execute")

    # AddScore(C, Points)
    g = bp.function("AddScore", inputs=["C:object:" + CONTROLLER, "Points:int"])
    r = g.call_self("FindRacer", inputs=[obj_pin("C", CONTROLLER)], outputs=[obj_pin("Racer", RC, "out")], pure=True)
    g.link_entry("C", r, "C")
    b = branch_on(g, (valid(g, (r, "Racer")), "ReturnValue"))
    g.link_entry("then", b, "execute")
    cur = get_on(g, RC, "Score", INT, (r, "Racer"))
    add = math2(g, "Add_IntInt", INT)
    g.link(cur, "Score", add, "A")
    g.link_entry("Points", add, "B")
    s = set_on(g, RC, "Score", INT, (r, "Racer"), value=(add, "ReturnValue"))
    g.link(b, "then", s, "execute")

    # GrantCheckpointTimeBonus(C): players only
    g = bp.function("GrantCheckpointTimeBonus", inputs=["C:object:" + CONTROLLER])
    pc = g.cast(PLAYER_CONTROLLER)
    g.link_entry("C", pc, "Object")
    g.link_entry("then", pc, "execute")
    rs = race_state(g)
    tcur = get_on(g, GSC, "RemainingTime", FLOAT, rs)
    bonus = g.var_get("CheckpointTimeBonus", FLOAT)
    add = math2(g, "Add_FloatFloat", FLOAT)
    g.link(tcur, "RemainingTime", add, "A")
    g.link(bonus, "CheckpointTimeBonus", add, "B")
    sett = set_on(g, GSC, "RemainingTime", FLOAT, race_state(g), value=(add, "ReturnValue"))
    g.link(pc, "then", sett, "execute")

    # NotifyLapCompleted(C)
    g = bp.function("NotifyLapCompleted", inputs=["C:object:" + CONTROLLER])
    r = g.call_self("FindRacer", inputs=[obj_pin("C", CONTROLLER)], outputs=[obj_pin("Racer", RC, "out")], pure=True)
    g.link_entry("C", r, "C")
    b = branch_on(g, (valid(g, (r, "Racer")), "ReturnValue"))
    g.link_entry("then", b, "execute")
    laps = add_int_on(g, RC, "LapsCompleted", (r, "Racer"), delta="1")
    g.link(b, "then", laps, "execute")
    pts = g.var_get("PointsPerLap", INT)
    sc = g.call_self("AddScore", inputs=[obj_pin("C", CONTROLLER), Pin("Points", INT)])
    g.link_entry("C", sc, "C")
    g.link(pts, "PointsPerLap", sc, "Points")
    g.exec(laps, sc)
    nxt = set_on(g, RC, "NextCheckpointIndex", INT, (r, "Racer"), default="1")
    g.exec(sc, nxt)

    # NotifyCheckpointPassed(C): Next = (Next + 1) mod Count (Count 0 -> Next + 1), then the time bonus
    g = bp.function("NotifyCheckpointPassed", inputs=["C:object:" + CONTROLLER])
    r = g.call_self("FindRacer", inputs=[obj_pin("C", CONTROLLER)], outputs=[obj_pin("Racer", RC, "out")], pure=True)
    g.link_entry("C", r, "C")
    b = branch_on(g, (valid(g, (r, "Racer")), "ReturnValue"))
    g.link_entry("then", b, "execute")
    nx = get_on(g, RC, "NextCheckpointIndex", INT, (r, "Racer"))
    inc = math2(g, "Add_IntInt", INT, b="1")
    g.link(nx, "NextCheckpointIndex", inc, "A")
    arr = g.var_get("Checkpoints", OBJECT, cls_ref(CPC), container="Array")
    cnt = g.call_array(ARR, "Array_Length", Pin("e", OBJECT, sub_object=cls_ref(CPC)), outputs=[Pin("ReturnValue", INT, "out")])
    g.link(arr, "Checkpoints", cnt, "TargetArray")
    safe = g.call_static(MATH, "Max", inputs=[Pin("A", INT), Pin("B", INT, default="1")], outputs=[Pin("ReturnValue", INT, "out")], pure=True)
    g.link(cnt, "ReturnValue", safe, "A")
    mod = math2(g, "Percent_IntInt", INT)
    g.link(inc, "ReturnValue", mod, "A")
    g.link(safe, "ReturnValue", mod, "B")
    gt0 = compare(g, "Greater_IntInt", INT, b="0")
    g.link(cnt, "ReturnValue", gt0, "A")
    pick = g.call_static(MATH, "SelectInt", inputs=[Pin("A", INT), Pin("B", INT), Pin("bPickA", BOOL)],
                         outputs=[Pin("ReturnValue", INT, "out")], pure=True)
    g.link(mod, "ReturnValue", pick, "A")
    g.link(inc, "ReturnValue", pick, "B")
    g.link(gt0, "ReturnValue", pick, "bPickA")
    setn = set_on(g, RC, "NextCheckpointIndex", INT, (r, "Racer"), value=(pick, "ReturnValue"))
    g.link(b, "then", setn, "execute")
    bonus = g.call_self("GrantCheckpointTimeBonus", inputs=[obj_pin("C", CONTROLLER)])
    g.link_entry("C", bonus, "C")
    g.exec(setn, bonus)

    # NotifyCheckpointReached(Racer, Checkpoint) -> bool
    g = bp.function("NotifyCheckpointReached", inputs=["Racer:object:" + CONTROLLER, "Checkpoint:" + obj_spec(BP_CHECKPOINT)],
                    outputs=["ReturnValue:bool"])
    active = get_on(g, GSC, "bRaceActive", BOOL, race_state(g))
    rsv = valid(g, race_state(g))
    r = g.call_self("FindRacer", inputs=[obj_pin("C", CONTROLLER)], outputs=[obj_pin("Racer", RC, "out")], pure=True)
    g.link_entry("Racer", r, "C")
    rv = valid(g, (r, "Racer"))
    nx = get_on(g, RC, "NextCheckpointIndex", INT, (r, "Racer"))
    idx = g.var_get_on(CPC, "CheckpointIndex", INT)
    g.link_entry("Checkpoint", idx, "self")
    eq = compare(g, "EqualEqual_IntInt", INT)
    g.link(idx, "CheckpointIndex", eq, "A")
    g.link(nx, "NextCheckpointIndex", eq, "B")
    a1, a2, a3 = and_bool(g), and_bool(g), and_bool(g)
    g.link(rsv, "ReturnValue", a1, "A")
    g.link(active, "bRaceActive", a1, "B")
    g.link(a1, "ReturnValue", a2, "A")
    g.link(rv, "ReturnValue", a2, "B")
    g.link(a2, "ReturnValue", a3, "A")
    g.link(eq, "ReturnValue", a3, "B")
    b = branch_on(g, (a3, "ReturnValue"))
    g.link_entry("then", b, "execute")
    no = g.function_result([Pin("ReturnValue", BOOL, default="false")])
    g.link(b, "else", no, "execute")
    slc = g.var_set_on(RC, "LastCheckpoint", OBJECT, sub_object=cls_ref(CPC))
    g.link(r, "Racer", slc, "self")
    g.link_entry("Checkpoint", slc, "LastCheckpoint")
    g.link(b, "then", slc, "execute")
    now = game_time(g)
    slt = set_on(g, RC, "LastCheckpointTime", FLOAT, (r, "Racer"), value=(now, "ReturnValue"))
    g.exec(slc, slt)
    idx2 = g.var_get_on(CPC, "CheckpointIndex", INT)
    g.link_entry("Checkpoint", idx2, "self")
    is0 = compare(g, "EqualEqual_IntInt", INT, b="0")
    g.link(idx2, "CheckpointIndex", is0, "A")
    b0 = branch_on(g, (is0, "ReturnValue"), (slt, "then"))
    lap = g.call_self("NotifyLapCompleted", inputs=[obj_pin("C", CONTROLLER)])
    g.link_entry("Racer", lap, "C")
    g.link(b0, "then", lap, "execute")
    bonus = g.call_self("GrantCheckpointTimeBonus", inputs=[obj_pin("C", CONTROLLER)])
    g.link_entry("Racer", bonus, "C")
    g.exec(lap, bonus)
    passed = g.call_self("NotifyCheckpointPassed", inputs=[obj_pin("C", CONTROLLER)])
    g.link_entry("Racer", passed, "C")
    g.link(b0, "else", passed, "execute")
    yes = g.function_result([Pin("ReturnValue", BOOL, default="true")])
    g.exec(bonus, yes)
    g.exec(passed, yes)

    # HandleRacerDeath(C): count a life, game over at MaxDeaths, else schedule the respawn
    g = bp.function("HandleRacerDeath", inputs=["C:object:" + CONTROLLER])
    active = get_on(g, GSC, "bRaceActive", BOOL, race_state(g))
    rsv = valid(g, race_state(g))
