    st = set_on(g, RC, "LastPickupTime", FLOAT, (r, "Racer"), value=(now, "ReturnValue"))
    g.link(ba, "then", st, "execute")
    sty = set_on(g, RC, "LastPickupType", BYTE, (r, "Racer"), value=("entry", "Type"), sub=enum_ref(struct_path(E_ITEM_TYPE)))
