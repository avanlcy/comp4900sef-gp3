    bonus = g.call_self("GrantCheckpointTimeBonus", inputs=[obj_pin("C", CONTROLLER)])
    g.link_entry("C", bonus, "C")
    g.exec(setn, bonus)

    # NotifyCheckpointReached(Racer, Checkpoint) -> bool
    g = bp.function("NotifyCheckpointReached", doc="A car crossed a gate: credited only when it is the racer's next gate and the race is active.", inputs=["Racer:object:" + CONTROLLER, "Checkpoint:" + obj_spec(BP_CHECKPOINT)],
                    outputs=["ReturnValue:bool"])
    active = get_on(g, GSC, "bRaceActive", BOOL, race_state(g))
    rsv = valid(g, race_state(g))
    r = g.call_self("FindRacer", inputs=[obj_pin("C", CONTROLLER)], outputs=[obj_pin("Racer", RC, "out")], pure=True)
    g.link_entry("Racer", r, "C")
    rv = valid(g, (r, "Racer"))
    nx = get_on(g, RC, "NextCheckpointIndex", INT, (r, "Racer"))
    idx = g.var_get_on(CPC, "CheckpointIndex", INT)
    g.link_entry("Checkpoint", idx, "self")
    eq = compare(g, "EqualEqual_IntInt", INT)
    g.link(idx, "CheckpointIndex", eq, "A")
    g.link(nx, "NextCheckpointIndex", eq, "B")
    a1, a2, a3 = and_bool(g), and_bool(g), and_bool(g)
    g.link(rsv, "ReturnValue", a1, "A")
    g.link(active, "bRaceActive", a1, "B")
    g.link(a1, "ReturnValue", a2, "A")
    g.link(rv, "ReturnValue", a2, "B")
    g.link(a2, "ReturnValue", a3, "A")
    g.link(eq, "ReturnValue", a3, "B")
    b = branch_on(g, (a3, "ReturnValue"))
    g.link_entry("then", b, "execute")
    no = g.function_result([Pin("ReturnValue", BOOL, default="false")])
    g.link(b, "else", no, "execute")
    slc = g.var_set_on(RC, "LastCheckpoint", OBJECT, sub_object=cls_ref(CPC))
    g.link(r, "Racer", slc, "self")
    g.link_entry("Checkpoint", slc, "LastCheckpoint")
    g.link(b, "then", slc, "execute")
    now = game_time(g)
    slt = set_on(g, RC, "LastCheckpointTime", FLOAT, (r, "Racer"), value=(now, "ReturnValue"))
