"""Builds the Dead Fire art: art/catalog.json, tools/artgen/THIRD_PARTY.md and the generated textures and images.
Entries whose source is Poly Haven are downloaded (polyhaven.py) instead of generated.

    python -I tools/artgen/build_all.py [--kind all|catalog|textures|images|meshes|sounds|fonts|terrain] [--only NAME ...]

Meshes need Blender 5.2 (blender_path.py); --only limits the textures, images and meshes kinds to the named catalogue
entries (a texture set by its name, e.g. T_DF_Rock).
Sounds are generated by sfx.py (--only takes SW_DF_ names). Fonts (Task 18) are copied from tools/artgen/fonts/, where each is
kept beside its licence, to art/ (the catalogue's Font.file is relative to art/, like every other entry).
Terrain (Task 19) runs terrain.py on each catalogue terrain's track export, tools/artgen/data/tracks/<MapName>.json
(df_export_tracks.py), into art/terrain/ (--only takes terrain or map names, e.g. Switchback), then rewrites
art/catalog.json, whose MI_DF_Terrain_* instances carry the new terrain.json origin.
"""
import argparse
import datetime
import json
import os
import shutil
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from artgen import build_meshes, catalog, images, polyhaven, sfx, terrain, textures  # noqa: E402

ART = os.path.join(os.path.dirname(os.path.dirname(HERE)), "art")
TRACKS = os.path.join(HERE, "data", "tracks")
KINDS = ("catalog", "textures", "images", "meshes", "sounds", "fonts", "terrain")


def _fetch_dates():
    """slug -> the earliest fetch date in the lock (the lock is the record of what was downloaded, and when)."""
    dates = {}
    if os.path.exists(polyhaven.LOCK_PATH):
        with open(polyhaven.LOCK_PATH, encoding="utf-8") as f:
            for v in json.load(f).values():
                dates[v["slug"]] = min(v["fetched"], dates.get(v["slug"], v["fetched"]))
    return dates


def write_third_party(path):
    lines = [
        "# Third-party assets",
        "",
        "Generated by `tools/artgen/build_all.py`; do not edit by hand.",
        "",
        "- Russo One (`tools/artgen/fonts/RussoOne-Regular.ttf`, copied to `art/fonts/` by `build_all.py --kind fonts`): "
        "https://fonts.google.com/specimen/Russo+One, SIL Open Font License 1.1. "
        "The licence text is kept beside the font (`tools/artgen/fonts/OFL.txt`).",
    ]
    entries = catalog.polyhaven_entries()
    dates = _fetch_dates()
    for e in entries:
        slug = catalog.polyhaven_slug(e)
        authors = ", ".join(polyhaven.info(slug).get("authors", {})) or "Poly Haven"
        lines.append("- %s: https://polyhaven.com/a/%s, CC0, by %s, fetched %s. Reason: %s"
                     % (e.name, slug, authors, dates.get(slug, datetime.date.today().isoformat()), e.reason))
    if not entries:
        lines.append("- No Poly Haven assets are used.")
    lines += ["", "Some textures and models: Poly Haven (polyhaven.com), CC0", ""]
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


def build_textures(out_dir, only=None):
    written = []
    for ts in catalog.TEXTURES:
        if only and ts.name not in only:
            continue
        if ts.source == "gen":
            written += textures.build(ts, out_dir)
        else:
            slug, res = ts.source.split(":", 1)[1].split("@", 1)
            written += polyhaven.fetch_texture(slug, res, out_dir, ts.name[len("T_DF_"):])
    return written


def build_images(out_dir, only=None):
    written = []
    for im in catalog.IMAGES:
        if im.recipe not in ("todo", "terrain") and (not only or im.name in only):  # splats: build_terrains
            written += images.build(im, out_dir)
    return written


def build_terrains(out_dir, only=None):
    """terrain.py for every catalogue terrain; prints one summary line each and returns the files written."""
    written = []
    for map_name, name in catalog.TERRAINS.items():
        if only and name not in only and map_name not in only:
            continue
        t0 = time.time()
        res = terrain.build(os.path.join(TRACKS, map_name + ".json"), out_dir, catalog.TERRAIN_SEEDS[name])
        written += res["files"]
        print("%s: origin %s, heights %s cm, road samples %s cm, %d scatter instances, %.1f s"
              % (name, res["origin"], res["height_cm"], res["road_cm"], sum(res["scatter"].values()), time.time() - t0))
    return written


def build_all_meshes(out_dir, only=None):
    """Runs Blender for every mesh with a recipe (script not "todo"); writes <name>.fbx and <name>.json for each."""
    n = 0
    for m in catalog.MESHES:
        if m.script != "todo" and (not only or m.name in only):
            build_meshes.build(m, out_dir)
            n += 2
    return n


def build_sounds(out_dir, only=None):
    n = 0
    for sw in catalog.SOUNDS:
        if sw.recipe != "todo" and (not only or sw.name in only):
            sfx.build(sw, out_dir)
            n += 1
    return n


def build_fonts(only=None):
    """Copies each catalogue font from tools/artgen/<file> to art/<file> (Task 18); returns the number copied."""
    n = 0
    for f in catalog.FONTS:
        if not only or f.name in only:
            dst = os.path.join(ART, f.file)
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copyfile(os.path.join(HERE, f.file), dst)
            n += 1
    return n


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--kind", choices=("all",) + KINDS, default="all")
    ap.add_argument("--only", nargs="+", default=None, help="catalogue names; limits the textures, images, meshes, sounds and fonts kinds")
    args = ap.parse_args()
    kind = args.kind
    n = 0
    if kind in ("all", "catalog"):
        catalog.write_json(os.path.join(ART, "catalog.json"))
        write_third_party(os.path.join(HERE, "THIRD_PARTY.md"))
        n += 2
    if kind in ("all", "textures"):
        n += len(build_textures(os.path.join(ART, "textures"), args.only))
    if kind in ("all", "images"):
        n += len(build_images(os.path.join(ART, "images"), args.only))
    if kind in ("all", "meshes"):
        n += build_all_meshes(os.path.join(ART, "meshes"), args.only)
    if kind in ("all", "sounds"):
        n += build_sounds(os.path.join(ART, "sounds"), args.only)
    if kind in ("all", "fonts"):
        n += build_fonts(args.only)
    if kind in ("all", "terrain"):
        n += len(build_terrains(os.path.join(ART, "terrain"), args.only))
        catalog.write_json(os.path.join(ART, "catalog.json"))  # the terrain instances' TerrainOrigin
        n += 1
    print("ARTGEN OK: %d files" % n)


if __name__ == "__main__":
    main()
